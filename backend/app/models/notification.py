from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base

NOTIFICATION_TYPES = (
    "proposal_received",
    "proposal_accepted",
    "proposal_rejected",
    "proposal_expired",
    "rental_starting",
    "return_due",
    "rental_overdue",
    "return_requested",
    "rental_completed",
    "rental_canceled",
)
# Generated by the worker; at most one per (user_id, type, rental_id).
WORKER_NOTIFICATION_TYPES = ("rental_starting", "return_due", "rental_overdue")


class Notification(Base):
    """A notice for one user. The database stores data, never the sentence (RN-68).

    The payload must not carry e-mail, CPF, phone, address or full name.
    """

    __tablename__ = "notifications"
    __table_args__ = (
        CheckConstraint(
            "type IN ('proposal_received', 'proposal_accepted', 'proposal_rejected', "
            "'proposal_expired', 'rental_starting', 'return_due', 'rental_overdue', "
            "'return_requested', 'rental_completed', 'rental_canceled')",
            name="ck_notifications_type",
        ),
        CheckConstraint("jsonb_typeof(payload) = 'object'", name="ck_notifications_payload_object"),
        CheckConstraint(
            "NOT (payload ?| ARRAY['email', 'cpf', 'phone', 'full_name', 'address', 'cep', "
            "'street', 'number', 'complement', 'neighborhood'])",
            name="ck_notifications_payload_no_personal_data",
        ),
        CheckConstraint(
            "NOT (type IN ('rental_starting', 'return_due', 'rental_overdue')) "
            "OR rental_id IS NOT NULL",
            name="ck_notifications_worker_types_have_rental",
        ),
        Index("ix_notifications_user_id_created_at_id", "user_id", "created_at", "id"),
        Index(
            "uq_notifications_worker_user_type_rental",
            "user_id",
            "type",
            "rental_id",
            unique=True,
            postgresql_where=text("type IN ('rental_starting', 'return_due', 'rental_overdue')"),
        ),
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=False), primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", name="fk_notifications_user_id_users"),
        nullable=False,
    )
    type: Mapped[str] = mapped_column(Text, nullable=False)
    rental_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("rentals.id", name="fk_notifications_rental_id_rentals")
    )
    payload: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, server_default=text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )
    read_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

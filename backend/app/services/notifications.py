"""Notices: the internal emitter and the inbox of one user (F-46, F-47, F-52; RN-68).

`create_notification` is what the other tasks call to emit a notice. It only adds the row to the
caller's transaction, so the notice is saved or undone together with the action that caused it.
The inbox functions below only ever touch the rows of the user who is asking.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime
from typing import Any

from sqlalchemy import and_, func, or_, select, text, update
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.orm import Session

from app.errors import ApiError
from app.models import Notification, User
from app.models.notification import NOTIFICATION_TYPES, WORKER_NOTIFICATION_TYPES
from app.services.feed import _decode_cursor, _encode_cursor

MAX_BIGINT = 2**63 - 1

# The keys the database refuses in the payload (ck_notifications_payload_no_personal_data),
# checked here too so the caller gets a clear error instead of a constraint violation.
PERSONAL_DATA_KEYS = frozenset(
    {
        "email",
        "cpf",
        "phone",
        "full_name",
        "address",
        "cep",
        "street",
        "number",
        "complement",
        "neighborhood",
    }
)

# Predicate of the partial unique index that keeps the worker idempotent (H022-1).
_WORKER_INDEX_WHERE = text(
    "type IN (" + ", ".join(f"'{name}'" for name in WORKER_NOTIFICATION_TYPES) + ")"
)


def create_notification(
    db: Session,
    user_id: uuid.UUID,
    type: str,
    rental_id: int | None,
    payload: dict[str, Any],
) -> Notification | None:
    """Add a notice for `user_id` to the caller's transaction; nothing is committed here.

    The payload carries only identifiers, titles, dates and roles, never personal data. The types
    generated by the worker are unique per (user, type, rental): a repeated call creates nothing
    and returns None, which keeps the task idempotent. Any other type always creates a notice.
    """
    if type not in NOTIFICATION_TYPES:
        raise ValueError(f"Unknown notification type: {type}")
    if not isinstance(payload, dict):
        raise ValueError("The payload of a notification must be a JSON object.")
    personal = PERSONAL_DATA_KEYS & payload.keys()
    if personal:
        raise ValueError("The payload must not carry personal data: " + ", ".join(sorted(personal)))

    if type in WORKER_NOTIFICATION_TYPES:
        if rental_id is None:
            raise ValueError(f"The notification type {type} needs a rental_id.")
        statement = (
            pg_insert(Notification)
            .values(user_id=user_id, type=type, rental_id=rental_id, payload=payload)
            .on_conflict_do_nothing(
                index_elements=["user_id", "type", "rental_id"],
                index_where=_WORKER_INDEX_WHERE,
            )
            .returning(Notification.id)
        )
        new_id = db.scalar(statement)
        return db.get(Notification, new_id) if new_id is not None else None

    notification = Notification(user_id=user_id, type=type, rental_id=rental_id, payload=payload)
    db.add(notification)
    db.flush()
    return notification


def _decode_inbox_cursor(cursor: str) -> tuple[datetime, int]:
    created_at, notification_id = _decode_cursor(cursor)
    if notification_id > MAX_BIGINT:
        raise ApiError(status_code=400, code="INVALID_CURSOR", message="Cursor inválido.")
    return created_at, notification_id


def list_notifications(db: Session, user: User, limit: int, cursor: str | None) -> dict[str, Any]:
    """Newest first, by key (created_at, id), so scrolling never repeats or skips a notice."""
    mine = Notification.user_id == user.id
    total = db.scalar(select(func.count(Notification.id)).where(mine)) or 0
    conditions = [mine]
    if cursor:
        created_at, notification_id = _decode_inbox_cursor(cursor)
        conditions.append(
            or_(
                Notification.created_at < created_at,
                and_(Notification.created_at == created_at, Notification.id < notification_id),
            )
        )
    rows = db.scalars(
        select(Notification)
        .where(*conditions)
        .order_by(Notification.created_at.desc(), Notification.id.desc())
        .limit(limit + 1)
    ).all()
    items = list(rows[:limit])
    next_cursor = None
    if len(rows) > limit:
        next_cursor = _encode_cursor(items[-1].created_at, items[-1].id)
    return {"items": items, "next_cursor": next_cursor, "total": total}


def count_unread(db: Session, user: User) -> int:
    unread = select(func.count(Notification.id)).where(
        Notification.user_id == user.id, Notification.read_at.is_(None)
    )
    return db.scalar(unread) or 0


def mark_notification_read(db: Session, user: User, notification_id: int) -> None:
    owner_id = db.scalar(select(Notification.user_id).where(Notification.id == notification_id))
    if owner_id is None:
        raise ApiError(
            status_code=404, code="NOTIFICATION_NOT_FOUND", message="Aviso não encontrado."
        )
    if owner_id != user.id:
        raise ApiError(status_code=403, code="FORBIDDEN", message="Este aviso não é seu.")
    # Only an unread notice changes, so reading it again keeps the first read_at.
    db.execute(
        update(Notification)
        .where(Notification.id == notification_id, Notification.read_at.is_(None))
        .values(read_at=datetime.now(UTC))
    )
    db.commit()


def mark_all_notifications_read(db: Session, user: User) -> None:
    db.execute(
        update(Notification)
        .where(Notification.user_id == user.id, Notification.read_at.is_(None))
        .values(read_at=datetime.now(UTC))
    )
    db.commit()

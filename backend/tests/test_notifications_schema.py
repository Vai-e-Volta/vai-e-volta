"""H022-1: notifications table (RN-68) and the idempotency index for the worker."""

from __future__ import annotations

import os
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pytest
from alembic.config import Config
from sqlalchemy import Connection, create_engine, inspect, text
from sqlalchemy.exc import IntegrityError

from alembic import command
from app.migrations import upgrade_database

InsertRow = Callable[..., Any]
INSERT = (
    "INSERT INTO notifications (user_id, type, rental_id, payload) "
    "VALUES (:u, :t, :r, CAST(:p AS jsonb))"
)


def test_h022_1_migration_downgrade_and_upgrade() -> None:
    upgrade_database()
    config = Config(str(Path(__file__).resolve().parents[1] / "alembic.ini"))
    command.downgrade(config, "20261117_0004")
    engine = create_engine(os.environ["DATABASE_URL"])
    try:
        assert "notifications" not in inspect(engine).get_table_names()
        upgrade_database()
        assert "notifications" in inspect(engine).get_table_names()
    finally:
        engine.dispose()


def test_h022_1_worker_types_are_unique_per_user_type_and_rental(
    db: Connection, insert_user: InsertRow, insert_rental: InsertRow
) -> None:
    user_id = insert_user()
    rental_id = insert_rental()
    payload = '{"rental_id": 1, "role": "owner"}'

    for notification_type in ("rental_starting", "return_due", "rental_overdue"):
        params = {"u": user_id, "t": notification_type, "r": rental_id, "p": payload}
        db.execute(text(INSERT), params)
        with pytest.raises(IntegrityError), db.begin_nested():
            db.execute(text(INSERT), params)
        # ON CONFLICT DO NOTHING over the partial index keeps the job idempotent.
        inserted = db.execute(
            text(
                INSERT + " ON CONFLICT (user_id, type, rental_id) WHERE type IN "
                "('rental_starting', 'return_due', 'rental_overdue') DO NOTHING"
            ),
            params,
        )
        assert inserted.rowcount == 0

    # The other party of the same rental gets its own notice.
    other_user = insert_user()
    db.execute(text(INSERT), {"u": other_user, "t": "return_due", "r": rental_id, "p": payload})

    # Types generated by the API are not covered by the partial unique index.
    for _ in range(2):
        db.execute(
            text(INSERT), {"u": user_id, "t": "proposal_rejected", "r": rental_id, "p": "{}"}
        )


def test_h022_1_checks_type_payload_and_defaults(db: Connection, insert_user: InsertRow) -> None:
    user_id = insert_user()
    notification_id = db.scalar(
        text(
            "INSERT INTO notifications (user_id, type) VALUES (:u, 'proposal_expired') RETURNING id"
        ),
        {"u": user_id},
    )
    row = db.execute(
        text(
            "SELECT payload, read_at, rental_id, created_at IS NOT NULL "
            "FROM notifications WHERE id = :id"
        ),
        {"id": notification_id},
    ).one()
    assert row == ({}, None, None, True)

    for notification_type, payload in (
        ("unknown_type", "{}"),
        ("proposal_received", "[]"),
        ("proposal_received", '{"email": "x@example.invalid"}'),
        ("proposal_received", '{"cpf": "00000000000"}'),
        ("proposal_received", '{"phone": "00000000000"}'),
        ("proposal_received", '{"full_name": "Pessoa Ficticia"}'),
        ("proposal_received", '{"address": "Rua Ficticia"}'),
    ):
        with pytest.raises(IntegrityError), db.begin_nested():
            db.execute(
                text(INSERT), {"u": user_id, "t": notification_type, "r": None, "p": payload}
            )

    for rental_id in (-1, None):
        with pytest.raises(IntegrityError), db.begin_nested():
            db.execute(text(INSERT), {"u": user_id, "t": "return_due", "r": rental_id, "p": "{}"})
